// Pretty-printed examples for auditing label quality (sim/samples/EXAMPLES.md).

function fmtState(state: Record<string, unknown>): string {
  const lines: string[] = [];
  for (const [k, v] of Object.entries(state)) {
    if (Array.isArray(v)) {
      lines.push(`${k}:`);
      for (const x of v) lines.push(`  - ${typeof x === "string" ? x : JSON.stringify(x)}`);
    } else lines.push(`${k}: ${typeof v === "string" ? v : JSON.stringify(v)}`);
  }
  return lines.join("\n");
}

export function renderExamples(rows: Record<string, unknown>[]): string {
  // Diversity: every trigger, then non-passive best actions and rare diagnoses, then diagnosis-only and ask rows.
  const seen = new Set<string>();
  const picked: Record<string, unknown>[] = [];
  const meta = (r: Record<string, unknown>) => r.meta as Record<string, unknown>;
  const add = (r: Record<string, unknown> | undefined) => {
    if (!r || picked.includes(r)) return;
    picked.push(r);
  };
  const decision = rows.filter((r) => meta(r).trigger !== "ask" && !meta(r).diagnosis_only);
  const want: [string, (r: Record<string, unknown>) => boolean][] = [
    ["stale discard", (r) => meta(r).trigger === "mutation" && meta(r).diagnosis === "stale" && meta(r).best === "discard"],
    ["conflict", (r) => meta(r).diagnosis === "conflict"],
    ["duplicate request coalesce/block", (r) => meta(r).trigger === "request" && meta(r).diagnosis === "duplicate" && meta(r).passive_best === false],
    ["benign repeat send", (r) => meta(r).trigger === "request" && meta(r).diagnosis === "expected" && meta(r).passive_best === true && JSON.stringify(r.state).includes("identical")],
    ["failure serve_cached/retry", (r) => meta(r).trigger === "failure" && meta(r).passive_best === false],
    ["failure deliver", (r) => meta(r).trigger === "failure" && meta(r).passive_best === true],
    ["stall", (r) => meta(r).trigger === "stall"],
    ["inconsistency genuine", (r) => meta(r).trigger === "inconsistency" && meta(r).diagnosis === "inconsistent"],
    ["inconsistency coincidental", (r) => meta(r).trigger === "inconsistency" && meta(r).diagnosis === "expected"],
    ["transition", (r) => meta(r).trigger === "transition"],
    ["error", (r) => meta(r).trigger === "error"],
    ["benign concurrency apply", (r) => meta(r).trigger === "mutation" && meta(r).diagnosis === "expected" && meta(r).passive_best === true],
  ];
  for (const [, f] of want) add(decision.find(f));
  for (const r of decision) {
    const k = `${meta(r).trigger}|${meta(r).best}|${meta(r).diagnosis}`;
    if (picked.length >= 13) break;
    if (seen.has(k)) continue;
    seen.add(k);
    add(r);
  }
  add(rows.find((r) => meta(r).diagnosis_only));
  for (const r of rows.filter((x) => meta(x).trigger === "ask").slice(0, 2)) add(r);
  const out: string[] = ["# Sample rows (auto-generated by `node sim/dist/gen.js --sample`)", "", "Each example shows the situation exactly as the runtime handed it to the decider, the questions (after the documented transform), the labels, and the per-action counterfactual costs (lower is better; `adjusted` adds the tier premium / tie rule used for the soft label).", ""];
  picked.forEach((r, i) => {
    const m = r.meta as Record<string, unknown>;
    out.push(`## ${i + 1}. ${m.trigger} — ${m.domain} — ${String(r.family)}`, "");
    out.push(`id \`${r.id}\`, split \`${r.split}\`, chaos \`${m.chaos}\`, features ${JSON.stringify(m.features)}`, "");
    out.push("```text", fmtState(r.state as Record<string, unknown>), "```", "");
    out.push("Questions:", "```json", JSON.stringify(r.questions, null, 1), "```", "");
    out.push("Labels:", "```json", JSON.stringify(r.labels, null, 1), "```", "");
    if (m.costs) {
      out.push(`Costs: ${JSON.stringify(m.costs)}  `, `Adjusted: ${JSON.stringify(m.adjusted)}  `, `Sim diagnosis: \`${m.diagnosis}\`, best \`${m.best}\`, subject ${JSON.stringify(m.subject)}`, "");
      out.push("Cost parts:", "```json", JSON.stringify(m.cost_parts), "```", "");
    }
  });
  return out.join("\n");
}
